# Known failures from the yeetfollow tuning, see automotive/openpilot#4.
# Keyed by (force_decel, title); this base has no separate e2e/acc runs. Subtests
# can't carry an xfail marker, so strict=True is emulated: a known case that passes fails the test.
KNOWN_FAILURE_REASON = "known: yeetfollow tuning, see automotive/openpilot#4"
KNOWN_FAILURES = {
  *((False, title) for title in (
    'steady state following a car at 20m/s, then lead decel to 0mph at 2m/s^2',
    'steady state following a car at 20m/s, then lead decel to 0mph at 3m/s^2',
  )),
}


